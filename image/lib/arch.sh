#!/usr/bin/env bash
# Architecture helpers for agentic-arch. Source after wiki.sh (wiki_fm, wiki_body); needs yq, jq.
# ROOT is the repository root; the pages live in $ROOT/docs/architecture.
ARCH_DIR=docs/architecture
# shellcheck disable=SC2034  # used by agentic-arch
ARCH_GEN_NOTE='<!-- Generated by agentic-arch build from the pages in docs/architecture/. Do not edit. -->'
ARCH_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# arch_top: architecture.md front matter as JSON; fails when the file or its front matter is missing.
arch_top() { wiki_fm "$ROOT/$ARCH_DIR/architecture.md"; }

# arch_components: [{path, id, fm, body_lines}] for components/*.md; fm is null when invalid.
arch_components() {
  local f id fm n
  [ -d "$ROOT/$ARCH_DIR/components" ] || { echo '[]'; return 0; }
  while IFS= read -r f; do
    id="$(basename "$f" .md)"
    fm="$(wiki_fm "$f")" || fm=null
    n="$(wiki_body "$f" | grep -c . || true)"
    jq -cn --arg path "${f#"$ROOT"/}" --arg id "$id" --argjson fm "$fm" --argjson n "$n" \
      '{path: $path, id: $id, fm: $fm, body_lines: $n}'
  done < <(find "$ROOT/$ARCH_DIR/components" -maxdepth 1 -type f -name '*.md' | LC_ALL=C sort) | jq -s '.'
}

# arch_catalog_find KIND ID: the catalog file for a style, principle or pattern. The project wins
# over the overlay, the overlay over the built-in catalog. Non-zero when absent.
arch_catalog_find() {
  local kind="$1" id="$2" dir builtin found="" f
  builtin="${ARCH_CATALOG_BUILTIN:-}"
  if [ -z "$builtin" ]; then
    if [ -n "${AGENTIC_DIR:-}" ] && [ -d "$AGENTIC_DIR/skills/architect/catalog" ]; then
      builtin="$AGENTIC_DIR/skills/architect/catalog"
    else
      builtin="$ARCH_LIB_DIR/../../skills/architect/catalog"
    fi
  fi
  for dir in "$builtin" "${ARCH_CATALOG_OVERLAY:-/opt/agentic/catalog/architect}" "$ROOT/$ARCH_DIR/catalog"; do
    f="$dir/${kind}s/$id.md"
    if [ -f "$f" ]; then found="$f"; fi
  done
  [ -n "$found" ] || return 1
  printf '%s\n' "$found"
}

# arch_style_name ID: the catalog name of a style, the id when unknown.
arch_style_name() {
  local f name=""
  if f="$(arch_catalog_find style "$1")"; then
    name="$(wiki_fm "$f" 2>/dev/null | jq -r '.name // empty')" || name=""
  fi
  printf '%s\n' "${name:-$1}"
}

# arch_model: the model.json content as JSON (contract version 1). Components are ordered by part,
# module (none last), layer, id; connections by the owning module first, so one module's chain
# reads top to bottom, then in each component's talks_to order.
arch_model() {
  local top comps style_name
  top="$(arch_top)" || return 1
  comps="$(arch_components)"
  style_name="$(arch_style_name "$(jq -r '.style' <<<"$top")")"
  jq -n --argjson top "$top" --argjson comps "$comps" --arg sname "$style_name" '
    ($top.parts | map(.id)) as $pids
    | ([$top.parts[] | (.modules // [])[] | .id] | reduce .[] as $m ([]; if index($m) then . else . + [$m] end)) as $mods
    | def idx($xs; $x): if $x == null then 1000000 else ($xs | index($x)) // 999999 end;
      def lidx($p; $l): ($top.parts | map(select(.id == $p)) | first // {layers: []} | .layers | map(.id) | index($l)) // 999999;
      ($comps | map(select(.fm != null) | .fm + {cid: (.fm.id // .id)}
        | . + {part: (.part // $pids[0])})
        | map({id: .cid, name: (.name // .cid), part, layer, module: (.module // null), parent: (.parent // null),
               summary: (.summary // ""), page: "components/\(.cid).md", talks: (.talks_to // [])})
        | sort_by([idx($pids; .part), idx($mods; .module), lidx(.part; .layer), .id])) as $cs
    | {version: 1,
       style: {id: $top.style, name: $sname},
       parts: ($top.parts | map({id, name,
         layers: (.layers | map({id, name, mayUse})),
         modules: ((.modules // []) | map({id, name}))})),
       components: ($cs | map(del(.talks))),
       connections: ($cs | sort_by([idx($mods; .module), idx($pids; .part), lidx(.part; .layer), .id])
         | map(. as $c | .talks[] | {from: $c.id, to, via}))}'
}

# arch_owners: TSV "source<TAB>component" from the pages' sources; omitted paths map to "-".
arch_owners() {
  arch_components | jq -r '.[] | select(.fm != null) | (.fm.id // .id) as $id | (.fm.sources // [])[] | "\(.)\t\($id)"'
  if [ -f "$ROOT/$ARCH_DIR/omitted.yaml" ]; then
    yq -o=json -I0 '.paths // []' "$ROOT/$ARCH_DIR/omitted.yaml" | jq -r '.[] | select(type == "object") | "\(.path)\t-"'
  fi
}

# arch_links DIR TITLE: a line linking the pages of DIR (flows, decisions) when there are any.
arch_links() {
  local f parts="" t
  [ -d "$ROOT/$ARCH_DIR/$1" ] || return 0
  while IFS= read -r f; do
    [ "$(basename "$f")" = index.md ] && continue
    t="$(wiki_fm "$f" 2>/dev/null | jq -r '.title // .name // empty')" || t=""
    parts+="${parts:+, }[${t:-$(basename "$f" .md)}]($1/$(basename "$f"))"
  done < <(find "$ROOT/$ARCH_DIR/$1" -maxdepth 1 -type f -name '*.md' | LC_ALL=C sort)
  if [ -n "$parts" ]; then printf '%s: %s\n' "$2" "$parts"; fi
}

# arch_index: index.md text.
arch_index() {
  local top model
  top="$(arch_top)" || return 1
  model="$(arch_model)"
  printf '%s\n# Architecture\n\n' "$ARCH_GEN_NOTE"
  jq -r '"Style: \(.style.name)."' <<<"$model"
  printf '\n## Layers\n\n'
  jq -r '.parts[] | "- **\(.name)**: " + (.layers | map("\(.name) -> " + (if (.mayUse | length) == 0 then "nothing" else (.mayUse | join(", ")) end)) | join("; "))' <<<"$model"
  jq -r '"\nPrinciples, in order: " + (.principles | join(", ")) + ".",
    (if (.patterns | length) > 0 then "Patterns: " + (.patterns | join(", ")) + "." else empty end),
    (if ((.exceptions // []) | length) > 0 then "Accepted exceptions: " + (.exceptions | map(.id) | join(", ")) + "." else empty end)' <<<"$top"
  printf '\n## Components\n'
  jq -r '
    . as $m
    | def mname($p; $mid): if $mid == null then "Across modules" else ($m.parts[] | select(.id == $p) | .modules[] | select(.id == $mid) | .name) end;
      def lname($p; $l): $m.parts[] | select(.id == $p) | .layers[] | select(.id == $l) | .name;
      reduce $m.components[] as $c ({out: [], p: null, m: "-", l: null};
        (if $c.part != .p then .out += ["", "### " + ($m.parts[] | select(.id == $c.part) | .name)] | .m = "-" else . end
        | if $c.module != .m then .out += ["#### " + mname($c.part; $c.module)] | .l = null else . end
        | if $c.layer != .l then .out += ["##### " + lname($c.part; $c.layer)] else . end
        | .out += ["- [\($c.name)](\($c.page)): \($c.summary)"]
        | .p = $c.part | .m = $c.module | .l = $c.layer)) | .out[]' <<<"$model"
  printf '\n'
  arch_links flows Flows
  arch_links decisions Decisions
  printf '%s\n' "Paths are relative to docs/architecture/. Read the component page before changing its sources;" \
    "run the architect skill's plan mode on a plan when asked. The code wins over this doc."
}
