#!/usr/bin/env bash
# Wiki helpers for agentic-wiki: pages, front matter and generated blocks. Source it; needs yq and
# jq. ROOT is the repository root; the pages live in $ROOT/docs/wiki.
WIKI_DIR=docs/wiki
# shellcheck disable=SC2034  # used by agentic-wiki
WIKI_GEN_NOTE='<!-- Generated by agentic-wiki build from the pages in docs/wiki/. Do not edit. -->'

# wiki_fm FILE: the front matter as one line of JSON. Returns 2 without front matter, 1 when it
# is not a YAML mapping. CRLF files parse like LF.
wiki_fm() {
  local yaml json
  [ "$(head -n 1 "$1" | tr -d '\r')" = --- ] || return 2
  yaml="$(tr -d '\r' < "$1" | awk 'NR == 1 { next } /^---[[:space:]]*$/ { exit } { print }')"
  json="$(printf '%s\n' "$yaml" | yq -o=json -I0 '.' 2>/dev/null)" || return 1
  [ "$(jq -r 'type' <<<"$json")" = object ] || return 1
  printf '%s\n' "$json"
}

# wiki_body FILE: the lines after the front matter.
wiki_body() {
  tr -d '\r' < "$1" | awk 'NR == 1 && /^---[[:space:]]*$/ { fm = 1; next }
    fm && /^---[[:space:]]*$/ { fm = 0; next }
    !fm { print }'
}

# wiki_authored FILE: the body without generated blocks.
wiki_authored() {
  wiki_body "$1" | awk '/^<!-- generated:[a-z-]+:start -->$/ { skip = 1 }
    !skip { print }
    /^<!-- generated:[a-z-]+:end -->$/ { skip = 0 }'
}

# wiki_pages: the authored pages relative to ROOT, sorted; generated files are left out.
wiki_pages() {
  [ -d "$ROOT/$WIKI_DIR" ] || return 0
  (cd "$ROOT" && find "$WIKI_DIR" -type f -name '*.md' | LC_ALL=C sort) \
    | grep -vxF -e "$WIKI_DIR/index.md" -e "$WIKI_DIR/decisions/index.md" -e "$WIKI_DIR/reuse.md" || true
}

# wiki_model: every page as {path, id, fm}; fm is null when the front matter is missing or invalid.
wiki_model() {
  local f id fm
  while IFS= read -r f; do
    id="${f#"$WIKI_DIR"/}"; id="${id%.md}"
    fm="$(wiki_fm "$ROOT/$f")" || fm=null
    jq -cn --arg path "$f" --arg id "$id" --argjson fm "$fm" '{path: $path, id: $id, fm: $fm}'
  done < <(wiki_pages) | jq -s '.'
}

# wiki_put_block FILE NAME: replaces the generated block NAME with stdin, appends it when it is
# missing, and removes it when stdin is empty. Everything outside the block is kept.
wiki_put_block() {
  local file="$1" start="<!-- generated:$2:start -->" end="<!-- generated:$2:end -->" content
  content="$(cat)"
  if [ -f "$file" ] && grep -qxF -- "$start" "$file"; then
    S="$start" E="$end" C="$content" awk '
      $0 == ENVIRON["S"] { skip = 1; if (ENVIRON["C"] != "") { print; print ENVIRON["C"]; print ENVIRON["E"] } next }
      $0 == ENVIRON["E"] { skip = 0; next }
      !skip { print }' "$file" > "$file.tmp"
    mv "$file.tmp" "$file"
  elif [ -n "$content" ]; then
    { if [ -s "$file" ]; then cat "$file"; echo; fi
      printf '%s\n%s\n%s\n' "$start" "$content" "$end"; } > "$file.tmp"
    mv "$file.tmp" "$file"
  fi
}

# rule_globs FILE: the rule's paths joined by commas; empty when it has none.
rule_globs() {
  { wiki_fm "$1" || echo '{}'; } | jq -r '.paths // empty | if type == "array" then join(",") else . end'
}
