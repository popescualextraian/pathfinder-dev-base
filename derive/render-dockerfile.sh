#!/usr/bin/env bash
# Renders the derived Dockerfile from .agentic/agentic.yaml. The build context is .agentic/.
# Usage: render-dockerfile.sh [CONFIG_DIR]
set -euo pipefail
here="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
AGENTIC_DIR="${AGENTIC_DIR:-$(cd "$here/.." && pwd)}"
# shellcheck source=../image/lib/common.sh
source "$AGENTIC_DIR/lib/common.sh"
# shellcheck source=../image/lib/config.sh
source "$AGENTIC_DIR/lib/config.sh"
IMG=/opt/agentic   # paths as they are inside the image, whatever AGENTIC_DIR is here

cdir="${1:-${AGENTIC_CONFIG_MOUNT:-/agentic-config}}"
[ -f "$cdir/agentic.yaml" ] || { say "no agentic.yaml in $cdir"; exit 1; }
RESOLVED="$(mktemp)"
trap 'rm -f "$RESOLVED"' EXIT
config_resolve "$cdir" > "$RESOLVED"
if ! errs="$(config_validate "$RESOLVED")"; then printf '%s\n' "$errs" >&2; exit 1; fi

problems=()
# inside KEY: sets REL to the configured path relative to .agentic/ (the build context);
# records a problem when the path points outside it. Call directly, not in $(...).
inside() {
  local p; p="$(cfg "$1")"
  case "/$p/" in
    */../*) problems+=("${1#.}: $p must be inside .agentic/"); return 1 ;;
  esac
  case "$p" in
    .agentic/*) REL="${p#.agentic/}"; return 0 ;;
    *) problems+=("${1#.}: $p must be inside .agentic/"); return 1 ;;
  esac
}

installs=() envs=() paths=()
while IFS= read -r tool; do
  case "$tool" in apt|extra_dockerfile) continue ;; esac
  val="$(cfg_json ".tools[\"$tool\"]")"
  case "$val" in false|null) continue ;; esac
  if [ ! -f "$AGENTIC_DIR/tools/$tool.sh" ]; then
    problems+=("tools.$tool: no preset $tool in this image"); continue
  fi
  case "$(jq -r type <<<"$val")" in
    object) mapfile -t versions < <(jq -r '.versions[] | tostring' <<<"$val"); default="$(jq -r .default <<<"$val")" ;;
    array) mapfile -t versions < <(jq -r '.[]' <<<"$val"); default="${versions[0]:-}" ;;
    *) versions=("$(jq -r . <<<"$val")"); default="${versions[0]}" ;;
  esac
  [ "${#versions[@]}" -gt 0 ] || continue
  line=""
  for v in "${versions[@]}"; do
    line+="${line:+ && }bash $IMG/tools/$tool.sh install $v"
  done
  installs+=("RUN $line")
  while IFS= read -r kv; do
    [ -n "$kv" ] || continue
    if [ "${kv%%=*}" = PATH ]; then paths+=("${kv#PATH=}"); else envs+=("ENV $kv"); fi
  done < <(bash "$AGENTIC_DIR/tools/$tool.sh" env "$default")
done < <(jq -r '.tools | keys[]' "$RESOLVED")

extra=""; REL=""
# setup lines: CA copies go before the tools (downloads may need them), build lines after the
# user's Dockerfile, one cached RUN each; run-phase lines travel as the agentic.run label.
dt="$(jq -r '(.targets // ["claude","copilot"]) | join(",")' "$RESOLVED")"
ca_copies=() steps=() run_tsv="" applies=0
while IFS= read -r l; do
  parse_line "$l" || { problems+=("setup: $l: $L_ERR"); continue; }
  case "$L_KIND" in
    copy)
      if [ ! -e "$cdir/$L_SRC" ]; then problems+=("setup: $l: $L_SRC is not in .agentic/"); continue; fi
      c="COPY --chown=dev $(jq -cn --arg s "$L_SRC" --arg d "$L_DEST" '[$s, $d]')"
      if [[ "$L_DEST" == /usr/local/share/ca-certificates/* ]]; then ca_copies+=("$c"); else steps+=("$c"); fi ;;
    marketplace|plugin|mcp)
      steps+=("RUN $(jq -cn --arg t "$dt" --arg l "$l" '["agentic-apply", "--default-targets", $t, $l]')")
      applies=1 ;;
    mount) run_tsv+="$(printf 'mount\t%s\t%s\t%s\t%s' "$L_SRC" "$L_DEST" "$L_OPT" "$l")"$'\n' ;;
    volume) run_tsv+="$(printf 'volume\t%s\t%s\t\t%s' "$L_KEY" "$L_DEST" "$l")"$'\n' ;;
    workspace) if [ "$L_OPT" = path ]; then run_tsv+="$(printf 'bind\t%s\t%s\t\t%s' "$L_SRC" "$L_DEST" "$l")"$'\n'; fi ;;
  esac
done < <(jq -r '.setup // [] | .[]' "$RESOLVED")
if inside .tools.extra_dockerfile && [ -f "$cdir/$REL" ]; then extra="$REL"; fi
if [ "${#problems[@]}" -gt 0 ]; then printf '%s\n' "${problems[@]}" >&2; exit 1; fi

hash="$(sha256sum < "$RESOLVED" | cut -c1-16)"
socket=false; if cfg_true .docker.socket; then socket=true; fi

echo "# Generated by agentic build from .agentic/agentic.yaml. Do not edit."
echo "FROM $(cfg .base_image)"
echo "USER root"
echo "ARG UID=1000"
echo "ARG GID=1000"
# shellcheck disable=SC2016  # $UID/$GID are expanded by docker build, not here
echo 'RUN agentic-remap-user "$UID" "$GID"'
if [ "${#ca_copies[@]}" -gt 0 ]; then printf '%s\n' "${ca_copies[@]}"; echo "RUN update-ca-certificates"; fi
mapfile -t apt < <(jq -r '.tools.apt[]?' "$RESOLVED")
if [ "${#apt[@]}" -gt 0 ]; then
  echo "RUN apt-get update && apt-get install -y --no-install-recommends ${apt[*]} && rm -rf /var/lib/apt/lists/*"
fi
printf '%s\n' "${installs[@]}"
if [ "${#envs[@]}" -gt 0 ]; then printf '%s\n' "${envs[@]}"; fi
if [ "${#paths[@]}" -gt 0 ]; then echo "ENV PATH=$(IFS=:; echo "${paths[*]}"):\${PATH}"; fi
echo "RUN agentic-trust-java"
if [ -n "$extra" ]; then
  echo "# .agentic/$extra"
  # shellcheck disable=SC1003  # GNU sed '$a\' appends a newline only when one is missing
  sed -e '$a\' "$cdir/$extra"
fi
echo "USER dev"
echo "RUN agentic-trust-nss && agentic-render-toolchains"
for a in skills agents commands instructions.md; do
  if [ -e "$cdir/$a" ]; then echo "COPY --chown=dev $(jq -cn --arg s "$a" --arg d "/opt/agentic/project/$a" '[$s, $d]')"; fi
done
if [ "$applies" = 1 ]; then
  echo "ARG AGENTIC_SETUP_REFRESH=0"
  echo 'RUN ["agentic-apply","--baseline"]'
fi
if [ "${#steps[@]}" -gt 0 ]; then printf '%s\n' "${steps[@]}"; fi
if [ "$applies" = 1 ]; then echo 'RUN ["agentic-apply","--finish"]'; fi
echo "USER root"
echo "RUN agentic-inventory > /opt/agentic/inventory.txt"
echo "USER dev"
echo "LABEL agentic.project=\"$(cfg .project)\" agentic.config.hash=\"$hash\" agentic.docker_socket=\"$socket\" agentic.harness=\"$(cfg .harness.default)\" agentic.run=\"$(printf '%s' "$run_tsv" | base64 -w0)\""
echo "WORKDIR /work"
